import assert from 'node:assert/strict';
import test from 'node:test';
import {formatTranscript,sanitizeDeviceResult,transcriptFailure,transcriptSrt} from '../lib/device-relay.ts';

const result={videoId:'jNQXAC9IVRw',title:'Me at the zoo',method:'android-device',language:'en',languageName:'English',isAutoGenerated:false,availableLanguages:[],
 segments:[{start:1.2,duration:2.2,text:'first line'},{start:5,duration:3,text:'second line'}]};

test('device results are marked as YouTube captions',()=>{
 const r=sanitizeDeviceResult({...result,source:'local_asr',model:'x'},'jNQXAC9IVRw') as Record<string,unknown>;
 assert.equal(r.source,'youtube_captions');
 assert.equal(r.model,undefined);
 assert.equal((formatTranscript({segments:[{start:0,duration:1,text:'a'}]},'text') as Record<string,unknown>).source,'youtube_captions');
});

test('compact text keeps timestamps',()=>{
 const r=formatTranscript(sanitizeDeviceResult(result,'jNQXAC9IVRw'),'text') as Record<string,unknown>;
 assert.equal(r.transcript,'[00:01] first line\n[00:05] second line');
});

test('SRT cues use segment durations, or the next start',()=>{
 assert.equal(transcriptSrt([{start:29.4,duration:19.8,text:'first\nline'},{start:3661,duration:0,text:'b'}]),
  '1\n00:00:29,400 --> 00:00:49,200\nfirst line\n\n2\n01:01:01,000 --> 01:01:04,000\nb\n');
 assert.match(String((formatTranscript(result,'srt') as Record<string,unknown>).srt),/^1\n00:00:01,200 --> 00:00:03,400\nfirst line\n/);
});

test('videos without captions get a plain no_captions answer',()=>{
 for(const e of ["Aucune piste de sous-titres pour cette vidéo.","Cette vidéo n'a pas de sous-titres YouTube (ni manuels, ni automatiques) : aucune transcription n'est disponible."]){
  const r=transcriptFailure('abc',e) as Record<string,unknown>;
  assert.equal(r.status,'no_captions');
  assert.match(String(r.messageForUser),/no transcript/);
 }
 assert.equal((transcriptFailure('abc','HTTP 403') as Record<string,unknown>).deviceError,'HTTP 403');
});
