import assert from 'node:assert/strict';
import test from 'node:test';
import {formatTranscript,jobProgress,sanitizeDeviceResult,transcriptSrt,LOCAL_ASR_GUIDANCE} from '../lib/device-relay.ts';

const local={source:'local_asr',model:'whisper-small-int8',status:'complete',processingSeconds:93,languagesDetected:['ja','en','<script>'],languageHint:'ja',
 videoId:'UtU5tJDp68o',title:'Song',durationSeconds:190,method:'android-device:local-asr-whisper',language:'ja',languageName:'Japanese',isAutoGenerated:false,availableLanguages:[],
 segments:[{start:29.4,duration:19.8,text:'first line'},{start:49.2,duration:20,text:'second line'}]};

test('local transcripts keep provenance, sanitized',()=>{
 const r=sanitizeDeviceResult(local,'UtU5tJDp68o') as Record<string,unknown>;
 assert.equal(r.source,'local_asr');
 assert.equal(r.method,'android-device-local-asr');
 assert.equal(r.model,'whisper-small-int8');
 assert.deepEqual(r.languagesDetected,['ja','en']);
 assert.equal(r.languageHint,'ja');
 assert.equal(r.durationSeconds,190);
});

test('caption results stay marked as YouTube captions',()=>{
 const r=sanitizeDeviceResult({...local,source:undefined,model:undefined},'UtU5tJDp68o') as Record<string,unknown>;
 assert.equal(r.source,'youtube_captions');
 assert.equal(r.model,undefined);
 assert.equal((formatTranscript({segments:[{start:0,duration:1,text:'a'}]},'text') as Record<string,unknown>).source,'youtube_captions');
});

test('assistant gets guidance and timestamped text for local transcripts',()=>{
 const r=formatTranscript(sanitizeDeviceResult(local,'UtU5tJDp68o'),'text') as Record<string,unknown>;
 assert.equal(r.guidance,LOCAL_ASR_GUIDANCE);
 assert.equal(r.transcript,'[00:29] first line\n[00:49] second line');
});

test('SRT cues use segment durations, or the next start',()=>{
 assert.equal(transcriptSrt([{start:29.4,duration:19.8,text:'first\nline'},{start:3661,duration:0,text:'b'}]),
  '1\n00:00:29,400 --> 00:00:49,200\nfirst line\n\n2\n01:01:01,000 --> 01:01:04,000\nb\n');
 const r=formatTranscript(local,'srt') as Record<string,unknown>;
 assert.match(String(r.srt),/^1\n00:00:29,400 --> 00:00:49,200\nfirst line\n/);
});

test('progress is read only from claimed jobs',()=>{
 assert.deepEqual(jobProgress({status:'claimed',result:{progress:{phase:'transcription',percent:40,at:'x'}}}),{phase:'transcription',percent:40,at:'x'});
 assert.equal(jobProgress({status:'done',result:{progress:{phase:'audio'}}}),null);
 assert.equal(jobProgress({status:'claimed',result:null}),null);
});
