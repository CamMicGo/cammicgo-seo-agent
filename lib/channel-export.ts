/**
 * Batch transcripts of a YouTube channel: lists the uploads with the YouTube Data API, queues one
 * transcript job per video for the paired device, and assembles every video (metadata + full
 * timestamped transcript) into ONE document, e.g. a single NotebookLM source.
 */
import {createHmac} from 'node:crypto';
import {sb,createJob,transcriptText} from '@/lib/device-relay';

export type GoogleGet=(url:string)=>Promise<unknown>;
export type ExportVideo={id:string;title:string;publishedAt:string;duration?:string;views?:string;description?:string;language:string};
export type ChannelExport={id:string;user_id:string;channel_id:string;channel_title:string|null;language:string;videos:ExportVideo[];updated_at:string};
type DoneJob={video_id:string;status:string;error:string|null;result:{language?:string;languageName?:string;isAutoGenerated?:boolean;translatedFrom?:string;segments?:Array<{start:number;duration:number;text:string}>}|null;completed_at:string|null};

const BASE='https://seo.cammicgo.com';
export const MAX_BATCH_VIDEOS=100;

/** Unguessable export key derived from the server secret; no storage needed, stable across refreshes. */
export function exportKey(id:string){const k=process.env.SESSION_ENCRYPTION_KEY;if(!k)throw Error('SESSION_ENCRYPTION_KEY not configured');return createHmac('sha256',k).update('channel-export:'+id).digest('base64url').slice(0,32);}
export const exportUrl=(id:string)=>BASE+'/api/exports/'+id+'?key='+exportKey(id);

function apiError(v:unknown){return v&&typeof v==='object'&&'error' in v?(v as {error:unknown}).error:null;}

/** Accepts a channel ID (UC…), an @handle or a channel URL. */
export async function resolveChannel(input:string,get:GoogleGet){
 const s=input.trim();
 const id=s.match(/(UC[A-Za-z0-9_-]{22})/)?.[1];
 const handle=s.match(/@([A-Za-z0-9._-]{3,30})/)?.[1];
 if(!id&&!handle)return {error:'Give a channel ID (UC…), an @handle or a channel URL. Use youtube_find_channels to look one up by name.'};
 const r=await get('https://www.googleapis.com/youtube/v3/channels?part=snippet,contentDetails,statistics&'+(id?'id='+id:'forHandle=@'+encodeURIComponent(handle!))) as {items?:Array<{id:string;snippet?:{title?:string};contentDetails?:{relatedPlaylists?:{uploads?:string}}}>};
 if(apiError(r))return {error:'YouTube Data API error',details:r};
 const ch=r.items?.[0];
 const uploads=ch?.contentDetails?.relatedPlaylists?.uploads;
 if(!ch||!uploads)return {error:'Channel not found'};
 return {id:ch.id,title:ch.snippet?.title??ch.id,uploads};
}

/** Latest uploads (newest first), with metadata and original audio language. 1 quota unit per 50 videos per call. */
export async function listUploads(uploads:string,max:number,publishedAfter:string|undefined,get:GoogleGet){
 const ids:string[]=[];let page:string|undefined;
 const after=publishedAfter?Date.parse(publishedAfter):0;
 while(ids.length<max){
  const r=await get('https://www.googleapis.com/youtube/v3/playlistItems?part=contentDetails&maxResults=50&playlistId='+uploads+(page?'&pageToken='+page:'')) as {items?:Array<{contentDetails?:{videoId?:string;videoPublishedAt?:string}}>;nextPageToken?:string};
  if(apiError(r))throw Error('YouTube playlist error');
  let stop=false;
  for(const it of r.items??[]){
   const v=it.contentDetails;if(!v?.videoId)continue;
   if(after&&v.videoPublishedAt&&Date.parse(v.videoPublishedAt)<after){stop=true;break}
   ids.push(v.videoId);if(ids.length>=max)break;
  }
  page=r.nextPageToken;if(stop||!page)break;
 }
 const videos:ExportVideo[]=[];
 for(let i=0;i<ids.length;i+=50){
  const r=await get('https://www.googleapis.com/youtube/v3/videos?part=snippet,contentDetails,statistics&id='+ids.slice(i,i+50).join(',')) as {items?:Array<{id:string;snippet?:{title?:string;publishedAt?:string;description?:string;defaultAudioLanguage?:string;defaultLanguage?:string};contentDetails?:{duration?:string};statistics?:{viewCount?:string}}>};
  if(apiError(r))throw Error('YouTube videos error');
  for(const v of r.items??[])videos.push({id:v.id,title:v.snippet?.title??v.id,publishedAt:v.snippet?.publishedAt??'',duration:v.contentDetails?.duration,views:v.statistics?.viewCount,
   description:(v.snippet?.description??'').slice(0,1500),language:((v.snippet?.defaultAudioLanguage||v.snippet?.defaultLanguage||'original').toLowerCase().split('-')[0])});
 }
 return videos.sort((a,b)=>b.publishedAt.localeCompare(a.publishedAt));
}

const langOk=(job:DoneJob,target:string)=>target==='original'||(job.result?.language??'').split('-')[0]===target.split('-')[0];

/** Latest finished / failed / pending job per video for this export. */
async function jobsFor(userId:string,videos:ExportVideo[],withResults:boolean){
 if(!videos.length)return new Map<string,DoneJob[]>();
 const since=new Date(Date.now()-30*86_400_000).toISOString();
 const rows=await sb<DoneJob[]>('/rest/v1/cmg_transcript_jobs?video_id=in.('+videos.map(v=>v.id).join(',')+')&created_at=gt.'+encodeURIComponent(since)
  +'&or='+encodeURIComponent('(user_id.eq.'+userId+',status.eq.done)')+'&select=video_id,status,error,completed_at'+(withResults?',result':',result->language')+'&order=created_at.desc');
 const map=new Map<string,DoneJob[]>();
 for(const r of rows){const list=map.get(r.video_id)??[];list.push(withResults?r:{...r,result:{language:(r as unknown as {language?:string}).language}});map.set(r.video_id,list);}
 return map;
}

export function videoState(video:ExportVideo,jobs:DoneJob[]|undefined){
 const done=jobs?.find(j=>j.status==='done'&&langOk(j,video.language));
 if(done)return {state:'ready' as const,job:done};
 const pending=jobs?.find(j=>j.status==='pending'||j.status==='claimed');
 if(pending)return {state:'queued' as const};
 const failed=jobs?.find(j=>j.status==='error');
 if(failed)return {state:'failed' as const,error:failed.error};
 return {state:'missing' as const};
}

/** Creates or refreshes the export, and queues the transcripts that are not available yet. */
export async function runBatch(userId:string,channel:{id:string;title:string},videos:ExportVideo[],language:string){
 for(const v of videos)if(language!=='original')v.language=language;
 const rows=await sb<ChannelExport[]>('/rest/v1/cmg_channel_exports?on_conflict=user_id,channel_id,language',{method:'POST',
  body:JSON.stringify({user_id:userId,channel_id:channel.id,channel_title:channel.title,language,videos,updated_at:new Date().toISOString()}),prefer:'resolution=merge-duplicates,return=representation'});
 const exp=rows[0];
 const jobs=await jobsFor(userId,videos,false);
 let ready=0,queued=0;
 for(const v of videos){
  const st=videoState(v,jobs.get(v.id));
  if(st.state==='ready'){ready++;continue}
  if(st.state==='queued'){queued++;continue}
  await createJob(userId,v.id,v.language,120);queued++;
 }
 return {exp,ready,queued};
}

export async function readExport(id:string,userId?:string){
 if(!/^[0-9a-f-]{36}$/i.test(id))return null;
 const rows=await sb<ChannelExport[]>('/rest/v1/cmg_channel_exports?id=eq.'+id+(userId?'&user_id=eq.'+userId:'')+'&select=*');
 return rows[0]??null;
}

export async function exportStatus(exp:ChannelExport){
 const jobs=await jobsFor(exp.user_id,exp.videos,false);
 const counts={ready:0,queued:0,failed:0,missing:0};const failures:Array<{videoId:string;title:string;error:string|null|undefined}>=[];
 for(const v of exp.videos){const st=videoState(v,jobs.get(v.id));counts[st.state]++;if(st.state==='failed')failures.push({videoId:v.id,title:v.title,error:st.error});}
 return {counts,failures:failures.slice(0,20)};
}

/** Requeues videos whose transcript is missing or failed. */
export async function retryMissing(exp:ChannelExport){
 const jobs=await jobsFor(exp.user_id,exp.videos,false);let n=0;
 for(const v of exp.videos){const st=videoState(v,jobs.get(v.id));if(st.state==='failed'||st.state==='missing'){await createJob(exp.user_id,v.id,v.language,120);n++;}}
 return n;
}

function isoDuration(d?:string){const m=d?.match(/PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?/);if(!m)return '';const [h,mi,s]=[m[1],m[2],m[3]].map(x=>Number(x||0));return (h?h+':':'')+String(mi).padStart(h?2:1,'0')+':'+String(s).padStart(2,'0');}

/** One Markdown document with every video's details and full timestamped transcript. */
export async function buildDocument(exp:ChannelExport){
 const jobs=await jobsFor(exp.user_id,exp.videos,true);
 const out:string[]=[];
 const ready=exp.videos.filter(v=>videoState(v,jobs.get(v.id)).state==='ready').length;
 out.push('# '+(exp.channel_title??exp.channel_id)+' — YouTube transcripts','',
  'Channel: https://www.youtube.com/channel/'+exp.channel_id,
  'Updated: '+exp.updated_at.slice(0,16).replace('T',' ')+' UTC · '+exp.videos.length+' videos · '+ready+' transcripts',
  'Language: '+(exp.language==='original'?'original spoken language of each video':exp.language),
  'Generated by CamMicGo SEO Agent (seo.cammicgo.com). Timecodes are [mm:ss] or [h:mm:ss] from the start of each video.','');
 out.push('## Contents','');
 exp.videos.forEach((v,i)=>out.push((i+1)+'. '+v.title+' ('+v.publishedAt.slice(0,10)+')'));
 out.push('');
 exp.videos.forEach((v,i)=>{
  const st=videoState(v,jobs.get(v.id));
  out.push('---','','## '+(i+1)+'. '+v.title,'',
   '- URL: https://www.youtube.com/watch?v='+v.id,
   '- Published: '+v.publishedAt.slice(0,10)+(v.duration?' · Duration: '+isoDuration(v.duration):'')+(v.views?' · Views: '+Number(v.views).toLocaleString('en-US'):''));
  if(st.state==='ready'&&st.job?.result?.segments){
   const r=st.job.result;
   out.push('- Transcript language: '+(r.languageName??r.language??'?')+(r.isAutoGenerated?' (auto-generated)':'')+(r.translatedFrom?' · translated by YouTube from '+r.translatedFrom:''));
   if(v.description)out.push('','### Description','',v.description.trim());
   out.push('','### Transcript','',transcriptText(r.segments??[]),'');
  }else{
   if(v.description)out.push('','### Description','',v.description.trim());
   out.push('','_Transcript not available yet ('+(st.state==='failed'?'failed: '+(st.error??'unknown error'):st.state)+')._','');
  }
 });
 return out.join('\n');
}
