package com.cammicgo.kamikoseo;

import org.json.JSONArray;
import org.json.JSONObject;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.HttpURLConnection;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Fetches timestamped YouTube captions from the device itself (residential IP).
 *
 * Strategy, in order:
 *  1. InnerTube player endpoint with the ANDROID client: its caption URLs do not
 *     require the web "pot" anti-bot token that now blanks most web caption URLs.
 *  2. ytInitialPlayerResponse embedded in the watch page (legacy fallback).
 *
 * A consent cookie is sent on every request so EU devices are not redirected to
 * consent.youtube.com. Only validated 11-character video IDs are ever requested.
 */
public final class TranscriptFetcher {

  public static final class Segment {
    public final double start, duration; public final String text;
    Segment(double start, double duration, String text) { this.start = start; this.duration = duration; this.text = text; }
  }

  public static final class Result {
    public String videoId, method, language, languageName, translatedFrom;
    public boolean autoGenerated;
    public final List<String> availableLanguages = new ArrayList<>();
    public final List<Segment> segments = new ArrayList<>();
  }

  static final String ANDROID_CLIENT_VERSION = "20.10.38";
  static final String ANDROID_UA = "com.google.android.youtube/" + ANDROID_CLIENT_VERSION + " (Linux; U; Android 14) gzip";
  static final String WEB_UA = "Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Mobile Safari/537.36";
  static final String CONSENT_COOKIE = "SOCS=CAI; CONSENT=YES+cb";
  static final int MAX_BYTES = 6_000_000;

  private TranscriptFetcher() {}

  // ---------- public API ----------

  /** Extracts a video ID from a URL, a shared text, or a bare ID. Returns null if invalid. */
  public static String videoId(String input) {
    if (input == null) return null;
    String s = input.trim();
    Matcher m = Pattern.compile("(?:[?&]v=|youtu\\.be/|/shorts/|/embed/|/live/)([A-Za-z0-9_-]{11})").matcher(s);
    if (m.find()) return m.group(1);
    return s.matches("[A-Za-z0-9_-]{11}") ? s : null;
  }

  public static Result fetch(String videoId, String language) throws IOException {
    if (videoId == null || !videoId.matches("[A-Za-z0-9_-]{11}")) throw new IOException("Identifiant de vidéo invalide.");
    String lang = (language == null || language.trim().isEmpty()) ? "original" : language.trim().toLowerCase(Locale.ROOT);
    if (!lang.equals("original") && !lang.matches("[a-z]{2,3}(-[a-z0-9]{2,8})?")) lang = "original";

    String html = null;
    String apiKey = null;
    StringBuilder diagnostics = new StringBuilder();

    try {
      html = http("https://www.youtube.com/watch?v=" + videoId + "&hl=en", null, WEB_UA, null);
      apiKey = firstGroup(html, "\"INNERTUBE_API_KEY\"\\s*:\\s*\"([A-Za-z0-9_-]+)\"");
    } catch (IOException e) {
      diagnostics.append("watch-page : ").append(e.getMessage()).append('\n');
    }

    // 1. InnerTube ANDROID client
    JSONObject player = null;
    try {
      player = innertubePlayer(videoId, apiKey);
      JSONArray tracks = tracksOf(player);
      if (tracks != null && tracks.length() > 0) return download(videoId, tracks, lang, "innertube-android");
      diagnostics.append("innertube-android : ").append(statusOf(player)).append('\n');
    } catch (IOException e) {
      diagnostics.append("innertube-android : ").append(e.getMessage()).append('\n');
    }

    // 2. Watch-page embedded player response
    if (html != null) {
      try {
        String json = embeddedJson(html, "ytInitialPlayerResponse");
        if (json != null) {
          JSONObject webPlayer = new JSONObject(json);
          JSONArray tracks = tracksOf(webPlayer);
          if (tracks != null && tracks.length() > 0) return download(videoId, tracks, lang, "watch-page");
          diagnostics.append("watch-page : ").append(statusOf(webPlayer)).append('\n');
        } else if (html.contains("consent.youtube.com")) {
          diagnostics.append("watch-page : page de consentement YouTube\n");
        } else {
          diagnostics.append("watch-page : réponse du lecteur absente\n");
        }
      } catch (Exception e) {
        diagnostics.append("watch-page : ").append(e.getMessage()).append('\n');
      }
    }

    throw new IOException("Aucune piste de sous-titres accessible.\n" + diagnostics.toString().trim());
  }

  // ---------- output formats ----------

  public static String toText(Result r) {
    StringBuilder b = new StringBuilder();
    b.append("Vidéo : ").append(r.videoId).append('\n')
     .append("Langue : ").append(r.languageName != null ? r.languageName : r.language)
     .append(r.autoGenerated && (r.languageName == null || !r.languageName.toLowerCase(Locale.ROOT).contains("auto")) ? " (générée automatiquement)" : "").append('\n')
     .append("Méthode : ").append(r.method).append(" · ").append(r.segments.size()).append(" segments\n\n");
    for (Segment s : r.segments) b.append('[').append(clock(s.start)).append("] ").append(s.text).append('\n');
    return b.toString();
  }

  /** Same shape as the CamMicGo MCP youtube_get_transcript success response. */
  public static String toJson(Result r) {
    try {
      JSONObject o = new JSONObject();
      o.put("videoId", r.videoId);
      o.put("method", "android-device:" + r.method);
      o.put("language", r.language);
      o.put("languageName", r.languageName == null ? r.language : r.languageName);
      o.put("isAutoGenerated", r.autoGenerated);
      if (r.translatedFrom != null) o.put("translatedFrom", r.translatedFrom);
      JSONArray langs = new JSONArray();
      for (String l : r.availableLanguages) langs.put(l);
      o.put("availableLanguages", langs);
      JSONArray segs = new JSONArray();
      for (Segment s : r.segments) {
        JSONObject j = new JSONObject();
        j.put("start", round3(s.start)); j.put("duration", round3(s.duration)); j.put("text", s.text);
        segs.put(j);
      }
      o.put("segments", segs);
      return o.toString(2);
    } catch (Exception e) {
      return "{\"error\":\"JSON serialization failed\"}";
    }
  }

  public static String clock(double seconds) {
    long t = (long) Math.floor(seconds);
    long h = t / 3600, m = (t % 3600) / 60, s = t % 60;
    return h > 0 ? String.format(Locale.ROOT, "%d:%02d:%02d", h, m, s) : String.format(Locale.ROOT, "%02d:%02d", m, s);
  }

  // ---------- InnerTube ----------

  static JSONObject innertubePlayer(String videoId, String apiKey) throws IOException {
    try {
      JSONObject client = new JSONObject();
      client.put("clientName", "ANDROID");
      client.put("clientVersion", ANDROID_CLIENT_VERSION);
      client.put("androidSdkVersion", 34);
      client.put("hl", "en");
      JSONObject context = new JSONObject();
      context.put("client", client);
      JSONObject body = new JSONObject();
      body.put("context", context);
      body.put("videoId", videoId);
      String url = "https://www.youtube.com/youtubei/v1/player" + (apiKey != null ? "?key=" + apiKey : "");
      String response = http(url, body.toString(), ANDROID_UA, "application/json");
      return new JSONObject(response);
    } catch (IOException e) {
      throw e;
    } catch (Exception e) {
      throw new IOException("réponse InnerTube illisible");
    }
  }

  static JSONArray tracksOf(JSONObject player) {
    if (player == null) return null;
    JSONObject captions = player.optJSONObject("captions");
    if (captions == null) return null;
    JSONObject renderer = captions.optJSONObject("playerCaptionsTracklistRenderer");
    return renderer == null ? null : renderer.optJSONArray("captionTracks");
  }

  static String statusOf(JSONObject player) {
    if (player == null) return "aucune réponse";
    JSONObject ps = player.optJSONObject("playabilityStatus");
    if (ps == null) return "aucune piste de sous-titres";
    String status = ps.optString("status", "?");
    String reason = ps.optString("reason", "");
    return "OK".equals(status) ? "vidéo lisible mais sans sous-titres" : status + (reason.isEmpty() ? "" : " — " + reason);
  }

  // ---------- track selection + download ----------

  static Result download(String videoId, JSONArray tracks, String lang, String method) throws IOException {
    JSONObject chosen = pickTrack(tracks, lang);
    String tlang = null;
    // Requested language missing: ask YouTube to translate the best source track into it.
    if (!"original".equals(lang) && !matches(chosen, lang) && chosen.optBoolean("isTranslatable", false)) tlang = lang;

    Result r = new Result();
    r.videoId = videoId; r.method = method;
    for (int i = 0; i < tracks.length(); i++) {
      String code = tracks.optJSONObject(i).optString("languageCode");
      if (!r.availableLanguages.contains(code)) r.availableLanguages.add(code);
    }
    String sourceCode = chosen.optString("languageCode");
    r.autoGenerated = "asr".equals(chosen.optString("kind"));
    if (tlang != null) {
      r.language = tlang;
      r.translatedFrom = sourceCode;
      r.languageName = tlang + " (traduit par YouTube depuis " + sourceCode + ")";
    } else {
      r.language = sourceCode;
      r.languageName = trackName(chosen);
    }

    String base = chosen.optString("baseUrl").replace("\\u0026", "&");
    if (base.startsWith("/")) base = "https://www.youtube.com" + base;
    URL u = new URL(base);
    if (!"https".equals(u.getProtocol()) || !u.getHost().endsWith("youtube.com") || !u.getPath().startsWith("/api/timedtext"))
      throw new IOException("URL de sous-titres inattendue.");
    base = base.replaceAll("&fmt=[^&]*", "").replaceAll("&tlang=[^&]*", "") + "&fmt=json3" + (tlang != null ? "&tlang=" + tlang : "");

    String body = http(base, null, ANDROID_UA, null);
    if (body.trim().isEmpty()) throw new IOException("Piste de sous-titres vide (" + method + ").");
    if (body.trim().startsWith("{")) parseJson3(body, r.segments); else parseXml(body, r.segments);
    if (r.segments.isEmpty()) throw new IOException("Piste de sous-titres sans texte (" + method + ").");
    return r;
  }

  static boolean matches(JSONObject t, String lang) {
    String code = t.optString("languageCode").toLowerCase(Locale.ROOT);
    return code.equals(lang) || code.split("-")[0].equals(lang.split("-")[0]);
  }

  /**
   * "original": the auto-generated track of the spoken audio (kind=asr), else the first track.
   * A language code: that language (manual, then auto-generated). If absent, the best source to
   * translate from: a human-made track first, then the original-audio track, then the first one.
   */
  static JSONObject pickTrack(JSONArray tracks, String lang) {
    JSONObject manualExact = null, autoExact = null, manualPrefix = null, autoPrefix = null, asr = null, manual = null;
    String base = lang.split("-")[0];
    for (int i = 0; i < tracks.length(); i++) {
      JSONObject t = tracks.optJSONObject(i);
      if (t == null) continue;
      String code = t.optString("languageCode").toLowerCase(Locale.ROOT);
      boolean auto = "asr".equals(t.optString("kind"));
      if (auto && asr == null) asr = t;
      if (!auto && manual == null) manual = t;
      if (code.equals(lang)) { if (auto) { if (autoExact == null) autoExact = t; } else if (manualExact == null) manualExact = t; }
      else if (code.split("-")[0].equals(base)) { if (auto) { if (autoPrefix == null) autoPrefix = t; } else if (manualPrefix == null) manualPrefix = t; }
    }
    if ("original".equals(lang)) return asr != null ? asr : tracks.optJSONObject(0);
    if (manualExact != null) return manualExact;
    if (autoExact != null) return autoExact;
    if (manualPrefix != null) return manualPrefix;
    if (autoPrefix != null) return autoPrefix;
    if (manual != null && manual.optBoolean("isTranslatable", false)) return manual;
    if (asr != null) return asr;
    return tracks.optJSONObject(0);
  }

  static String trackName(JSONObject t) {
    JSONObject name = t.optJSONObject("name");
    if (name == null) return null;
    String simple = name.optString("simpleText", "");
    if (!simple.isEmpty()) return simple;
    JSONArray runs = name.optJSONArray("runs");
    if (runs != null && runs.length() > 0) return runs.optJSONObject(0).optString("text", null);
    return null;
  }

  // ---------- caption parsers ----------

  static void parseJson3(String body, List<Segment> out) throws IOException {
    try {
      JSONArray events = new JSONObject(body).optJSONArray("events");
      if (events == null) return;
      for (int i = 0; i < events.length(); i++) {
        JSONObject e = events.optJSONObject(i);
        if (e == null || !e.has("tStartMs")) continue;
        JSONArray segs = e.optJSONArray("segs");
        if (segs == null) continue;
        StringBuilder text = new StringBuilder();
        for (int k = 0; k < segs.length(); k++) text.append(segs.optJSONObject(k).optString("utf8", ""));
        String clean = text.toString().replace('\n', ' ').replaceAll("\\s+", " ").trim();
        if (!clean.isEmpty()) out.add(new Segment(e.optLong("tStartMs") / 1000.0, e.optLong("dDurationMs", 0) / 1000.0, clean));
      }
    } catch (Exception e) {
      throw new IOException("Format json3 illisible.");
    }
  }

  /** Handles both legacy <text start="s" dur="s"> and srv3 <p t="ms" d="ms"> formats. */
  static void parseXml(String xml, List<Segment> out) {
    Matcher m = Pattern.compile("<(text|p)\\b([^>]*)>(.*?)</\\1>", Pattern.DOTALL).matcher(xml);
    while (m.find()) {
      boolean ms = "p".equals(m.group(1));
      String attrs = m.group(2);
      String startAttr = attr(attrs, ms ? "t" : "start");
      if (startAttr == null) continue;
      String durAttr = attr(attrs, ms ? "d" : "dur");
      double start = parse(startAttr), dur = durAttr == null ? 0 : parse(durAttr);
      if (ms) { start /= 1000.0; dur /= 1000.0; }
      String text = decodeEntities(m.group(3).replaceAll("<[^>]+>", "")).replace('\n', ' ').replaceAll("\\s+", " ").trim();
      if (!text.isEmpty()) out.add(new Segment(start, dur, text));
    }
  }

  static String attr(String attrs, String name) {
    Matcher m = Pattern.compile("\\b" + name + "=\"([0-9.]+)\"").matcher(attrs);
    return m.find() ? m.group(1) : null;
  }

  static double parse(String s) { try { return Double.parseDouble(s); } catch (NumberFormatException e) { return 0; } }

  /** Decodes &amp; first so double-encoded entities (&amp;#39;) resolve correctly. */
  static String decodeEntities(String s) {
    String r = s.replace("&amp;", "&").replace("&amp;", "&").replace("&quot;", "\"").replace("&apos;", "'").replace("&lt;", "<").replace("&gt;", ">").replace("&nbsp;", " ");
    Matcher m = Pattern.compile("&#(x?)([0-9A-Fa-f]+);").matcher(r);
    StringBuffer b = new StringBuffer();
    while (m.find()) {
      int code;
      try { code = Integer.parseInt(m.group(2), m.group(1).isEmpty() ? 10 : 16); } catch (NumberFormatException e) { code = '?'; }
      m.appendReplacement(b, Matcher.quoteReplacement(new String(Character.toChars(code))));
    }
    m.appendTail(b);
    return r.contains("&#") ? b.toString() : r;
  }

  static double round3(double v) { return Math.round(v * 1000.0) / 1000.0; }

  // ---------- helpers ----------

  static String firstGroup(String s, String regex) {
    Matcher m = Pattern.compile(regex).matcher(s);
    return m.find() ? m.group(1) : null;
  }

  /** Extracts the JSON object assigned to `marker` in a page, honouring strings and escapes. */
  static String embeddedJson(String html, String marker) {
    Matcher m = Pattern.compile(Pattern.quote(marker) + "\\s*=\\s*").matcher(html);
    if (!m.find()) return null;
    int brace = html.indexOf('{', m.end());
    if (brace < 0 || brace - m.end() > 5) return null;
    int depth = 0; boolean quote = false, escape = false;
    for (int i = brace; i < html.length(); i++) {
      char ch = html.charAt(i);
      if (quote) { if (escape) escape = false; else if (ch == '\\') escape = true; else if (ch == '"') quote = false; }
      else if (ch == '"') quote = true;
      else if (ch == '{') depth++;
      else if (ch == '}' && --depth == 0) return html.substring(brace, i + 1);
    }
    return null;
  }

  static String http(String url, String postBody, String userAgent, String contentType) throws IOException {
    HttpURLConnection c = (HttpURLConnection) new URL(url).openConnection();
    try {
      c.setConnectTimeout(12000);
      c.setReadTimeout(20000);
      c.setInstanceFollowRedirects(true);
      c.setRequestProperty("User-Agent", userAgent);
      c.setRequestProperty("Accept-Language", "en-US,en;q=0.9");
      c.setRequestProperty("Cookie", CONSENT_COOKIE);
      if (postBody != null) {
        c.setRequestMethod("POST");
        c.setDoOutput(true);
        c.setRequestProperty("Content-Type", contentType != null ? contentType : "application/json");
        c.setRequestProperty("Origin", "https://www.youtube.com");
        c.setRequestProperty("X-YouTube-Client-Name", "3");
        c.setRequestProperty("X-YouTube-Client-Version", ANDROID_CLIENT_VERSION);
        byte[] bytes = postBody.getBytes(StandardCharsets.UTF_8);
        c.setFixedLengthStreamingMode(bytes.length);
        try (OutputStream os = c.getOutputStream()) { os.write(bytes); }
      }
      int status = c.getResponseCode();
      if (status == 429) throw new IOException("HTTP 429 : trop de requêtes, YouTube limite temporairement cet appareil.");
      if (status != 200) throw new IOException("HTTP " + status);
      try (InputStream in = c.getInputStream()) {
        ByteArrayOutputStream b = new ByteArrayOutputStream();
        byte[] buf = new byte[8192]; int n;
        while ((n = in.read(buf)) != -1) { b.write(buf, 0, n); if (b.size() > MAX_BYTES) throw new IOException("Réponse trop volumineuse."); }
        return new String(b.toByteArray(), StandardCharsets.UTF_8);
      }
    } finally {
      c.disconnect();
    }
  }
}
